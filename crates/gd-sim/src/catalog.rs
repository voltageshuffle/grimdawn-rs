//! The attribute schema table: every Game.dll attribute class that loads
//! item / skill / character stats, and the DB field names it reads.
//! Field names and engine type ids only (no game data).
//!
//! # Provenance (Game.dll)
//!
//! One [`FieldDef`] per class, read from the class's own code:
//! - `ty`: the type id the constructor stores at `Attribute.type` (e.g.
//!   `CharAttributeVal_Strength`: 1, `DefenseAttributeAbs_Fire`: 6,
//!   `SkillAttributeVal_CooldownReduction`: 1)
//!   or, for the damage / retaliation classes, their `GetType` virtual.
//! - field names: the strings the constructor stores
//!   (`CharAttribute*`: `CharAttribute.valueTag`; `DefenseAttribute*`: value `DefenseAttribute.valueTag`,
//!   chance `DefenseAttribute.chanceTag`; `SkillAttribute*`: value `SkillAttribute.valueTag`, chance
//!   `SkillAttribute.chanceTag`)
//!   or that the `GetLoad*Tag` virtuals return (damage / retaliation classes:
//!   `GetLoadValueMinTag`, `GetLoadValueMaxTag`, `GetLoadChanceTag`, ... e.g.
//!   `DamageAttributeAbs_Fire`'s).
//!
//! # `ty`: three id spaces
//!
//! `ty` is read in the space of the entry's [`AttrFamily`]:
//! [`CombatType`](crate::attributes::CombatType) (`CombatAttributeType`) for
//! the offense / retaliation / defense / armor / weapon-base families,
//! [`CharAttr`](crate::attributes::CharAttr) (`CharAttributeType`) for the
//! character families, and the skill attribute type (1 cooldown reduction,
//! 2 energy cost reduction, 3 projectile speed, 4 combo charge spend) for
//! the skill families. The same number means different things across
//! spaces, so use `combat_type()` / `char_attr()` only on matching families.
//!
//! # Shared fields and the armor double entry
//!
//! A field name belongs to one class, except where the engine loads it in
//! two: `offensivePhysicalMin` / `Max` (`DamageAttribute_Physical` and the
//! weapon base `DamageAttribute_BasePhysical`) and
//! `defensiveBlockModifierChance` (`DefenseAttributeMisc_BlockAmountModifier`
//! and `DefenseAttributeMisc_BlockModifier`).
//!
//! `DefenseAttribute_BaseProtectionAbsorption` is the one class with two
//! entries: its `LoadFromTable` reads both `defensiveProtection`
//! and `defensiveBonusProtection`, and `FieldDef` has one value slot. The
//! `defensiveBonusProtection` entry comes first, so a class lookup
//! ([`class_def`](crate::attributes::class_def)) returns it; code that needs
//! both fields handles the class by name. Its `ty` is 0 (the
//! constructor leaves `Attribute.type` at 0; `AddToAccumulator`
//! emits a `CombatAttributeDefense_AbsorptionProtection`,
//! type 38), so `combat_type()` is `None` for armor.
//!
//! # Order and lookup
//!
//! Entries are grouped by family, classes sorted by name within it; this is
//! not an engine order (the damage stores' creation order is
//! [`DAMAGE_LOAD_ORDER`](crate::attributes::DAMAGE_LOAD_ORDER)).
//! [`family`](crate::attributes::family) returns a family's slice of the
//! table ([`FAMILY_RANGES`], checked contiguous at compile time).
//! [`lookup`](crate::attributes::lookup) returns the first entry in table
//! order loading a field (ASCII case-insensitive), so it resolves the shared
//! fields to `DamageAttribute_Physical` and
//! `DefenseAttributeMisc_BlockAmountModifier` (PORT: the engine never looks
//! a class up by field; each class loads its own fields).
use super::attributes::AttrFamily::{self, *};
use super::attributes::FieldDef;

pub static FIELDS: &[FieldDef] = TABLE;

/// Each [`AttrFamily`]'s `(start, end)` index range in [`FIELDS`].
pub(crate) const FAMILY_RANGES: [(usize, usize); AttrFamily::COUNT] = family_ranges();

const fn family_ranges() -> [(usize, usize); AttrFamily::COUNT] {
    let mut ranges = [(0, 0); AttrFamily::COUNT];
    let mut seen = [false; AttrFamily::COUNT];
    let mut i = 0;
    while i < TABLE.len() {
        let f = TABLE[i].family as usize;
        if i == 0 || TABLE[i - 1].family as usize != f {
            assert!(!seen[f], "FIELDS must group entries by family");
            seen[f] = true;
            ranges[f].0 = i;
        }
        ranges[f].1 = i + 1;
        i += 1;
    }
    ranges
}

